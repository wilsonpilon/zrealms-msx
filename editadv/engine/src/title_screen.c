static void DecompressPackBitsToVRAM(u16 vram_dest, const u8* src, u16 dest_size)
{
    u16 written = 0;
    while (written < dest_size)
    {
        i8 header = (i8)*src++;
        if (header >= 0)
        {
            u8 count = (u8)(header + 1);
            while (count--)
            {
                VDP_Poke_16K(*src++, (u16)(vram_dest + written));
                written++;
            }
        }
        else if (header != -128)
        {
            u8 count = (u8)(1 - header);
            u8 val = *src++;
            VDP_FillVRAM_16K(val, (u16)(vram_dest + written), count);
            written += count;
        }
    }
}
